"""Storage and owner-scoped admin views for editor attachments."""
import hashlib
import re
from pathlib import PurePath
from uuid import uuid4

from django.conf import settings
from django.core.files.storage import default_storage
from django.http import JsonResponse
from django.views.decorators.http import require_GET, require_POST
from django.utils.text import slugify


def _extension(uploaded):
    """Allow a small set of file types, checking their contents, not MIME headers."""
    header = uploaded.read(12)
    uploaded.seek(0)
    if header.startswith(b'\x89PNG\r\n\x1a\n'):
        return '.png'
    if header.startswith(b'\xff\xd8\xff'):
        return '.jpg'
    if header.startswith((b'GIF87a', b'GIF89a')):
        return '.gif'
    if header.startswith(b'RIFF') and header[8:12] == b'WEBP':
        return '.webp'
    suffix = PurePath(uploaded.name).suffix.lower()
    if suffix == '.pdf' and header.startswith(b'%PDF-'):
        return suffix
    if suffix in {'.zip', '.docx', '.xlsx', '.pptx'} and header.startswith(b'PK\x03\x04'):
        return suffix
    if suffix == '.txt':
        try:
            data = uploaded.read()
            data.decode('utf-8')
            if b'\x00' not in data:
                return suffix
        except UnicodeDecodeError:
            pass
        finally:
            uploaded.seek(0)
    return None


# Only names generated by this widget can be listed or deleted. The owner
# directory is derived on the server, never accepted from the client.
_FILENAME = re.compile(r'^[0-9a-f]{32}_[a-zA-Z0-9_-]{1,128}\.(?:png|jpg|gif|webp|pdf|txt|zip|docx|xlsx|pptx)$')


def _directory(user):
    owner = hashlib.sha256(str(user.pk).encode('utf-8')).hexdigest()
    return 'daisy/toastui/' + owner


def _serialize(directory, filename):
    return {
        'id': filename,
        'name': filename[33:],
        'url': default_storage.url(directory + '/' + filename),
    }


@require_POST
def upload(request):
    uploaded = request.FILES.get('file')
    limit = getattr(settings, 'DAISY_TOASTUI_EDITOR_MAX_UPLOAD_SIZE', 5 * 1024 * 1024)
    if not uploaded or not uploaded.size or uploaded.size > limit:
        return JsonResponse({'error': 'Missing file or file exceeds the size limit.'}, status=400)
    extension = _extension(uploaded)
    if not extension:
        return JsonResponse({'error': 'Unsupported or invalid file type.'}, status=400)
    directory = _directory(request.user)
    label = slugify(PurePath(uploaded.name).stem)[:64] or 'file'
    filename = uuid4().hex + '_' + label + extension
    path = default_storage.save(directory + '/' + filename, uploaded)
    parent, separator, filename = path.rpartition('/')
    if not separator or parent != directory or not _FILENAME.fullmatch(filename):
        default_storage.delete(path)
        return JsonResponse({'error': 'Storage returned an invalid filename.'}, status=500)
    return JsonResponse(_serialize(directory, filename))


@require_GET
def attachments(request):
    try:
        page = int(request.GET.get('page', 1))
        if not 1 <= page <= 1000000:
            raise ValueError
    except ValueError:
        return JsonResponse({'error': 'Invalid page.'}, status=400)
    directory = _directory(request.user)
    try:
        _, filenames = default_storage.listdir(directory)
    except FileNotFoundError:
        filenames = []
    except NotImplementedError:
        return JsonResponse({'error': 'This storage backend does not support listing attachments.'}, status=501)
    filenames = sorted((name for name in filenames if _FILENAME.fullmatch(name)), reverse=True)
    start = (page - 1) * 50
    return JsonResponse({
        'items': [_serialize(directory, name) for name in filenames[start:start + 50]],
        'has_more': len(filenames) > start + 50,
    })


@require_POST
def delete(request):
    filename = request.POST.get('id', '')
    if not _FILENAME.fullmatch(filename):
        return JsonResponse({'error': 'Attachment not found.'}, status=404)
    path = _directory(request.user) + '/' + filename
    if not default_storage.exists(path):
        return JsonResponse({'error': 'Attachment not found.'}, status=404)
    default_storage.delete(path)
    return JsonResponse({'deleted': True})
