"""Generate Tailwind source directives for an installed django-daisy app."""

import json
import sysconfig
from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError


class Command(BaseCommand):
    help = "Write Tailwind @source directives for django-daisy and project templates."

    def add_arguments(self, parser):
        parser.add_argument("--output", required=True, help="Generated CSS file to import from your Tailwind entrypoint.")
        parser.add_argument("--source", action="append", default=[], help="Additional file or directory to scan; may be repeated.")

    def handle(self, *args, **options):
        base = Path(settings.BASE_DIR).resolve()
        output = Path(options["output"]).resolve()
        paths = {Path(apps.get_app_config("django_daisy").path).resolve(), base / "templates"}
        site_dirs = {Path(sysconfig.get_path(key)).resolve() for key in ("purelib", "platlib")}
        for engine in settings.TEMPLATES:
            paths.update(Path(path).resolve() for path in engine.get("DIRS", []))
        for app in apps.get_app_configs():
            path = Path(app.path).resolve()
            # Include local app templates, Python and JavaScript, without scanning
            # every installed dependency or the project's virtual environment.
            if (path != base and base in path.parents and path.is_dir()
                    and not any(site == path or site in path.parents for site in site_dirs)):
                paths.add(path)
        paths.update(Path(path).resolve() for path in options["source"])
        # A previous output can be safely replaced; it contains generated data only.
        if output in paths:
            raise CommandError("The output file cannot also be a source.")
        lines = ["/* Generated by manage.py daisy_css_sources; do not edit. */"]
        lines.extend(f"@source {json.dumps(path.as_posix(), ensure_ascii=False)};" for path in sorted(paths))
        try:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text("\n".join(lines) + "\n", encoding="utf-8")
        except OSError as exc:
            raise CommandError(f"Could not write {output}: {exc}") from exc
        self.stdout.write(self.style.SUCCESS(f"Wrote Tailwind sources to {output}"))
